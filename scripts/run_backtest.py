def load_all_signals(data_dir_signals: str) -> pd.DataFrame:
    """Reads every outputs/signals/signals_<date>.jsonl into one stacked frame."""
    frames = []
    for path in sorted(glob.glob(os.path.join(data_dir_signals, "signals_*.jsonl"))):
        rows = []
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                rows.append(json.loads(line))
        if rows:
            frames.append(pd.DataFrame(rows))
    if not frames:
        return pd.DataFrame()
    return pd.concat(frames, ignore_index=True)


def load_scored_by_date(data_dir_processed: str, prefix: str) -> Dict[str, pd.DataFrame]:
    """Reads data/processed/<prefix>_<date>.csv for every date on disk (excludes any
    _bak_* backup subdirectories/files, which are pre-rerun snapshots, not live data)."""
    out: Dict[str, pd.DataFrame] = {}
    pattern = os.path.join(data_dir_processed, f"{prefix}_*.csv")
    for path in sorted(glob.glob(pattern)):
        fname = os.path.basename(path)
        if "_bak_" in fname:
            continue
        date_str = fname.replace(f"{prefix}_", "").replace(".csv", "")
        try:
            out[date_str] = pd.read_csv(path, dtype={"stock_id": str})
        except Exception as e:
            logger.warning(f"load_scored_by_date: failed to read {path}: {e}")
    return out


def load_finmind_ohlcv_history(data_dir_ohlcv: str) -> pd.DataFrame:
    """Reads every data/raw/ohlcv/finmind_<stock_id>.json into one stacked
    (stock_id, trade_date, open/high/low/close/volume) frame."""
    rows = []
    for path in sorted(glob.glob(os.path.join(data_dir_ohlcv, "finmind_*.json"))):
        fname = os.path.basename(path)
        if fname == "_smoke_twse_sample.json" or not fname.startswith("finmind_"):
            continue
        stock_id = fname.replace("finmind_", "").replace(".json", "")
        try:
            with open(path, "r", encoding="utf-8") as f:
                env = json.load(f)
        except Exception as e:
            logger.warning(f"load_finmind_ohlcv_history: unreadable {path}: {e}")
            continue
        for r in env.get("payload", []) or []:
            try:
                rows.append({
                    "stock_id": stock_id, "trade_date": r["date"],
                    "open": float(r["open"]), "high": float(r["max"]), "low": float(r["min"]),
                    "close": float(r["close"]), "volume": float(r.get("Trading_Volume") or 0.0),
                })
            except (KeyError, TypeError, ValueError):
                continue
    return pd.DataFrame(rows)


def load_adjustment_factors(data_dir: str) -> pd.DataFrame:
    """M7: reads data/reference/price_adjustment_factors.csv (built by
    scripts/fetch_price_adjustments.py). Empty DataFrame (not an error) if the file
    doesn't exist yet -- callers must treat every stock as UNADJUSTED in that case."""
    path = os.path.join(data_dir, "reference", "price_adjustment_factors.csv")
    if not os.path.exists(path):
        logger.warning(f"load_adjustment_factors: {path} not found -- all prices will be "
                        f"treated as UNADJUSTED (run scripts/fetch_price_adjustments.py first).")
        return pd.DataFrame(columns=["stock_id", "trade_date", "adj_factor"])
    return pd.read_csv(path, dtype={"stock_id": str})


def apply_price_adjustment(df_ohlcv: pd.DataFrame, data_dir: str, use_adjusted_prices: bool) -> tuple:
    """
    M7: if `use_adjusted_prices`, merges in adjustment factors and OVERWRITES
    open/high/low/close with the adjusted values wherever a factor is known (a new
    `price_unadjusted` bool column marks the rest, per-row, so status can be reported
    accurately even when adjustment is enabled but coverage is partial). If
    `use_adjusted_prices` is False, prices pass through unchanged and every row is
    marked `price_unadjusted=True` (honest: nothing was adjusted, not merely "wasn't
    tried"). Returns (df_ohlcv_possibly_adjusted, unadjusted_stock_pct).
    """
    if df_ohlcv.empty:
        return df_ohlcv, None
    if not use_adjusted_prices:
        out = df_ohlcv.copy()
        out["price_unadjusted"] = True
        return out, 1.0

    df_factors = load_adjustment_factors(data_dir)
    merged = apply_adjustment(df_ohlcv, df_factors)
    for raw_col, adj_col in (("open", "adj_open"), ("high", "adj_high"),
                              ("low", "adj_low"), ("close", "adj_close")):
        # Only overwrite where a real factor was found; price_unadjusted rows keep
        # their original raw value (apply_adjustment already does this per-row).
        merged[raw_col] = merged[adj_col]
    merged = merged.drop(columns=["adj_open", "adj_high", "adj_low", "adj_close"], errors="ignore")

    n_stocks_total = merged["stock_id"].nunique()
    n_stocks_unadjusted = merged.loc[merged["price_unadjusted"], "stock_id"].nunique()
    unadjusted_pct = round(n_stocks_unadjusted / n_stocks_total, 4) if n_stocks_total else None
    logger.info(f"apply_price_adjustment: {n_stocks_total - n_stocks_unadjusted}/{n_stocks_total} "
                f"stocks have real adjustment coverage; {n_stocks_unadjusted} UNADJUSTED "
                f"({unadjusted_pct:.1%} of universe) -- see backtest_summary JSON's "
                f"'unadjusted_stock_pct' field.")
    return merged, unadjusted_pct


def load_disposition_stock_ids(data_dir: str) -> dict:
    """
    M7: union of every stock_id that appeared on ANY disposition/attention raw-endpoint
    file on disk (across all dates -- this project only has TODAY's live snapshot, not
    a historical archive per date, since these endpoints themselves are "current status"
    APIs with no date-range query parameter; see src/disposition_fetcher.py module
    docstring). Returns {"disposition_stock_ids": set, "dates_covered": [...]} so the
    caller can honestly disclose this is a same-day-only signal, not a true historical
    per-event disposition history for the 60-day backtest window.
    """
    disp_dir = os.path.join(data_dir, "raw", "disposition")
    ids = set()
    dates_covered = set()
    if not os.path.isdir(disp_dir):
        return {"disposition_stock_ids": ids, "dates_covered": []}
    for path in sorted(glob.glob(os.path.join(disp_dir, "*.json"))):
        fname = os.path.basename(path)
        matched_key = None
        for key in DISPOSITION_ENDPOINTS:
            if fname.startswith(key + "_"):
                matched_key = key
                break
        if matched_key is None:
            continue
        date_str = fname.replace(matched_key + "_", "").replace(".json", "")
        dates_covered.add(date_str)
        try:
            with open(path, "r", encoding="utf-8") as f:
                envelope = json.load(f)
        except Exception as e:
            logger.warning(f"load_disposition_stock_ids: unreadable {path}: {e}")
            continue
        spec = DISPOSITION_ENDPOINTS[matched_key]
        for row in envelope.get("payload", []) or []:
            sid = DispositionFetcher._extract_stock_id(row, spec)
            if sid:
                ids.add(sid)
    return {"disposition_stock_ids": ids, "dates_covered": sorted(dates_covered)}


def load_taiex(data_dir_market_index: str) -> pd.DataFrame:
    path = os.path.join(data_dir_market_index, "finmind_index_twse.json")
    if not os.path.exists(path):
        logger.error(f"load_taiex: {path} not found -- market benchmark will be UNAVAILABLE.")
        return pd.DataFrame()
    with open(path, "r", encoding="utf-8") as f:
        env = json.load(f)
    rows = [{"trade_date": r["date"], "close": float(r["close"])} for r in env.get("payload", [])
            if r.get("close") is not None]
    return pd.DataFrame(rows)


def summarize_tier(df_events: pd.DataFrame, signal_type: str, horizon: int = None,
                    excess_col_prefix: str = "excess_return_net") -> dict:
    """Headline stats for one signal grade: independent event count, cost-adjusted
    excess-return median/mean, win rate. n<30 is explicitly flagged per SPEC_ADDENDUM
    B-3.3/M5c brief's "樣本不足不可裁決" instruction rather than silently reported as if
    decisive."""
    sub = df_events[df_events["signal_type"] == signal_type]
    horizon = horizon or 10
    col = f"{excess_col_prefix}_{horizon}d"
    if col not in sub.columns:
        return {"signal_type": signal_type, "n_events": len(sub), "n_realized": 0,
                "median_excess_pct": None, "mean_excess_pct": None, "win_rate": None,
                "sample_sufficient": False}
    realized = sub[col].dropna()
    n = len(realized)
    return {
        "signal_type": signal_type,
        "n_events": len(sub),
        "n_realized": n,
        "median_excess_pct": float(realized.median() * 100) if n > 0 else None,
        "mean_excess_pct": float(realized.mean() * 100) if n > 0 else None,
        "win_rate": float((realized > 0).mean()) if n > 0 else None,
        "sample_sufficient": n >= 30,
    }


def compare_vs_momentum_baseline(df_events: pd.DataFrame, df_momentum: pd.DataFrame,
                                  horizon: int = 10) -> dict:
    """SPEC_ADDENDUM A-3.3: signal excess return vs momentum-baseline excess return at
    the same horizon. Returns medians of each distribution and whether the signal median
    beats the baseline median -- a simple, disclosed comparison, NOT a formal
    significance test (no t-test/Mann-Whitney is run; SPEC_ADDENDUM only requires the
    comparison exist and be honestly reported, and this milestone's small n at most
    grades makes a formal test result likely underpowered/misleading if presented
    without heavy caveats better handled in report prose than a boolean)."""
    col = f"excess_return_net_{horizon}d"
    sig_vals = df_events[col].dropna() if col in df_events.columns else pd.Series(dtype=float)
    base_col = f"excess_return_{horizon}d"
    base_vals = df_momentum[base_col].dropna() if base_col in df_momentum.columns else pd.Series(dtype=float)
    sig_median = float(sig_vals.median() * 100) if len(sig_vals) > 0 else None
    base_median = float(base_vals.median() * 100) if len(base_vals) > 0 else None
    beats_baseline = (sig_median is not None and base_median is not None and sig_median > base_median)
    return {
        "horizon_days": horizon,
        "signal_n": len(sig_vals), "signal_median_excess_pct": sig_median,
        "baseline_n": len(base_vals), "baseline_median_excess_pct": base_median,
        "signal_beats_baseline": beats_baseline,
    }


