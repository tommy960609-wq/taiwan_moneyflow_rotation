def _write_df(ws, df: pd.DataFrame) -> None:
    from openpyxl.utils.dataframe import dataframe_to_rows
    if df is None or df.empty:
        ws["A1"] = "(no rows)"
        return
    for r in dataframe_to_rows(df, index=False, header=True):
        ws.append(r)


def run(data_dir: Optional[str] = None, output_dir: Optional[str] = None,
        n_bootstrap: int = 10000, report_date: Optional[str] = None,
        use_adjusted_prices: Optional[bool] = None) -> dict:
    data_dir = data_dir or _default_data_dir()
    output_dir = output_dir or _default_output_dir()
    report_date = report_date or datetime.date.today().isoformat()

    if use_adjusted_prices is None:
        use_adjusted_prices = bool(ConfigManager().get("backtest.use_adjusted_prices", True))

    logger.info("Loading signals, scored frames, OHLCV, TAIEX from disk...")
    df_signals = load_all_signals(os.path.join(output_dir, "signals"))
    df_sector_scored_by_date = load_scored_by_date(os.path.join(data_dir, "processed"), "sector_scored")
    df_stock_scored_by_date = load_scored_by_date(os.path.join(data_dir, "processed"), "stock_scored")
    df_ohlcv = load_finmind_ohlcv_history(os.path.join(data_dir, "raw", "ohlcv"))
    df_taiex = load_taiex(os.path.join(data_dir, "raw", "market_index"))

    n_stocks_finmind = df_ohlcv["stock_id"].nunique() if not df_ohlcv.empty else 0
    logger.info(f"Loaded {len(df_signals)} signal rows, {len(df_sector_scored_by_date)} sector-scored days, "
                f"{n_stocks_finmind} FinMind-covered stocks, {len(df_taiex)} TAIEX rows.")

    if df_signals.empty or df_ohlcv.empty or df_taiex.empty:
        logger.error("run_backtest: missing required inputs (signals/OHLCV/TAIEX). Aborting.")
        return {"status": "ABORTED_MISSING_INPUTS"}

    # M7: ex-dividend backward adjustment (config/default.yaml backtest.use_adjusted_prices,
    # default true). Stocks without a computed factor keep their raw price, tagged
    # UNADJUSTED (price_unadjusted=True) -- never silently mixed with adjusted prices
    # without a way to tell them apart downstream.
    df_ohlcv, unadjusted_stock_pct = apply_price_adjustment(df_ohlcv, data_dir, use_adjusted_prices)

    # M7: disposition/attention stock ids (same-day snapshot only -- see
    # load_disposition_stock_ids docstring for the honest scope limitation).
    disposition_info = load_disposition_stock_ids(data_dir)
    disposition_stock_ids = disposition_info["disposition_stock_ids"]
    logger.info(f"Loaded {len(disposition_stock_ids)} disposition/attention stock_ids "
                f"(same-day snapshot(s): {disposition_info['dates_covered']}).")

    bt = Backtester(fee_pct=0.001425, tax_pct=0.003, slippage_pct=0.001, limit_up_handling="exclude")
    df_events = bt.run_event_study(df_signals, df_stock_scored_by_date, df_ohlcv, df_taiex,
                                    horizons=HORIZONS_DAYS, disposition_stock_ids=disposition_stock_ids)
    logger.info(f"Event study produced {len(df_events)} independent events "
                f"(exclude accounting; see status_postpone columns for postpone accounting).")

    # UNTRADABLE accounting (both conventions, per SPEC_ADDENDUM B-2.1's "both metrics
    # must be reported for comparison")
    untradable_stats = {}
    if not df_events.empty:
        untradable_stats["total_events"] = len(df_events)
        untradable_stats["untradable_exclude"] = int((df_events["status"] == "UNTRADABLE").sum())
        untradable_stats["pending_exclude"] = int((df_events["status"] == "PENDING").sum())
        untradable_stats["tradable_exclude"] = int((df_events["status"] == "TRADABLE").sum())
        untradable_stats["untradable_postpone"] = int((df_events["status_postpone"] == "UNTRADABLE").sum())
        untradable_stats["tradable_postpone"] = int((df_events["status_postpone"] == "TRADABLE").sum())

    # Benchmarks (SPEC_ADDENDUM A-3)
    logger.info("Computing momentum-extension baseline...")
    df_momentum = momentum_extension_baseline(df_sector_scored_by_date, df_stock_scored_by_date,
                                               df_ohlcv, df_taiex, horizons=HORIZONS_DAYS)
    logger.info(f"Momentum baseline: {len(df_momentum)} daily observations.")

    logger.info(f"Computing random sector bootstrap baseline (N={n_bootstrap})...")
    df_random = random_sector_bootstrap_baseline(df_sector_scored_by_date, df_stock_scored_by_date,
                                                  df_ohlcv, df_taiex, n_draws=n_bootstrap,
                                                  horizons=HORIZONS_DAYS, random_seed=42)
    logger.info(f"Random baseline: {len(df_random)} resolved draws (requested {n_bootstrap}).")

    # Headline per-tier stats
    tiers = {}
    vs_momentum = {}
    for signal_type in sorted(df_events["signal_type"].dropna().unique()) if not df_events.empty else []:
        tiers[signal_type] = summarize_tier(df_events, signal_type, horizon=10)
        sub = df_events[df_events["signal_type"] == signal_type]
        vs_momentum[signal_type] = compare_vs_momentum_baseline(sub, df_momentum, horizon=10)

    n_param_combinations_tested = 1  # this milestone runs exactly one config (config/default.yaml
                                      # backtest.* + the single limit_up_handling="exclude" primary
                                      # convention, with postpone reported alongside for comparison,
                                      # not as a second tuned configuration) -- SPEC_ADDENDUM B-3.3
                                      # multiple-comparison disclosure.

    disclosures = [
        f"歷史 OHLCV {n_stocks_finmind}/1963 檔 -> 族群成分不完整，廣度/占比在歷史段是部分樣本",
        "法人/融資券歷史近乎缺失 (institutional/margin 覆蓋率低) -> 歷史訊號的法人因子=中性 50 回退",
        "門檻未校準 (config/default.yaml 全部標記 PLACEHOLDER - UNCALIBRATED)",
        "60 天全在同一市場環境，無環境分層 (SPEC §18 分層留待資料累積)",
        (f"M7: 除權息調整{'已啟用' if use_adjusted_prices else '未啟用 (use_adjusted_prices=false)'}"
         f"（來源: FinMind TaiwanStockDividendResult 自算調整因子，非官方調整價資料集——"
         f"官方 adjusted-price dataset 於本 token 不可用，見乾跑收據）；"
         f"UNADJUSTED（無調整因子可用，使用原始價）股票比例="
         f"{f'{unadjusted_stock_pct:.1%}' if unadjusted_stock_pct is not None else 'N/A'}"),
        (f"M7: 處置/注意股名單已接線，共 {len(disposition_stock_ids)} 檔 "
         f"(快照日期: {disposition_info['dates_covered']})——僅為「當前即時狀態」快照，"
         f"TWSE/TPEx 該類端點無歷史日期查詢參數，無法回溯 60 天視窗內每日的處置/注意狀態，"
         f"故本欄為同一組 id 套用到全部歷史事件，非逐日精確歸戶。"),
        "本輪測試參數組合數 = 1 (單一 config，postpone 為對照口徑而非第二組調參)",
        "結論等級：初步研究讀數 (PRELIMINARY RESEARCH READING)，非 Research Ready",
    ]

    headline = {"tiers": tiers, "vs_momentum": vs_momentum,
                "n_param_combinations_tested": n_param_combinations_tested,
                "use_adjusted_prices": use_adjusted_prices,
                "unadjusted_stock_pct": unadjusted_stock_pct,
                "disposition_stock_count": len(disposition_stock_ids)}

    report_path = os.path.join(output_dir, "backtests", f"backtest_report_{report_date}.xlsx")
    build_report_workbook(report_path, headline, df_events, df_momentum, df_random,
                           untradable_stats, disclosures)

    # Also dump the raw event/momentum/random frames as CSV for programmatic reuse /
    # verifier spot-checks (Excel round-tripping can lose float precision).
    csv_dir = os.path.join(output_dir, "backtests")
    df_events.to_csv(os.path.join(csv_dir, f"backtest_events_{report_date}.csv"), index=False, encoding="utf-8-sig")
    df_momentum.to_csv(os.path.join(csv_dir, f"backtest_momentum_baseline_{report_date}.csv"), index=False, encoding="utf-8-sig")
